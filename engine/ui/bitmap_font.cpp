bool BitmapFont::init(Renderer& renderer) {
    // Generate a white-on-transparent texture atlas
    // Each character is 5x7, laid out in a row
    atlas_width_ = NUM_CHARS * CHAR_WIDTH;
    atlas_height_ = CHAR_HEIGHT;

    std::vector<uint8_t> pixels(atlas_width_ * atlas_height_ * 4, 0);

    for (int ch = 0; ch < NUM_CHARS; ch++) {
        int base_x = ch * CHAR_WIDTH;

        for (int row = 0; row < CHAR_HEIGHT; row++) {
            uint8_t bits = FONT_DATA[ch][row];

            for (int col = 0; col < CHAR_WIDTH; col++) {
                // Bit 4 = leftmost pixel, bit 0 = rightmost
                bool pixel_on = (bits >> (CHAR_WIDTH - 1 - col)) & 1;

                if (pixel_on) {
                    int px = base_x + col;
                    int py = row;
                    int idx = (py * atlas_width_ + px) * 4;

                    pixels[idx + 0] = 255; // R
                    pixels[idx + 1] = 255; // G
                    pixels[idx + 2] = 255; // B
                    pixels[idx + 3] = 255; // A
                }
            }
        }
    }

    TextureInfo info = renderer.load_texture_from_memory(
        pixels.data(), atlas_width_, atlas_height_, 4);

    if (info.id == INVALID_TEXTURE) return false;

    font_texture_ = info.id;
    initialized_ = true;
    return true;
}

void BitmapFont::shutdown() {
    // Texture cleanup handled by renderer
    font_texture_ = INVALID_TEXTURE;
    initialized_ = false;
}

void BitmapFont::draw_text(Renderer& renderer, const std::string& text,
                            int x, int y, const Color& color,
                            int scale) const {
    if (!initialized_ || font_texture_ == INVALID_TEXTURE) return;

    int cx = x;
    int char_w = CHAR_WIDTH * scale;
    int char_h = CHAR_HEIGHT * scale;

    for (char c : text) {
        if (c == '\n') {
            cx = x;
            y += char_h + scale;
            continue;
        }

        int idx = static_cast<int>(c) - FIRST_CHAR;
        if (idx < 0 || idx >= NUM_CHARS) {
            cx += char_w + CHAR_SPACING * scale;
            continue;
        }

        Rect src(idx * CHAR_WIDTH, 0, CHAR_WIDTH, CHAR_HEIGHT);
        Rect dest(cx, y, char_w, char_h);

        renderer.draw_texture_colored(font_texture_, src, dest, color);

        cx += char_w + CHAR_SPACING * scale;
    }
}

int BitmapFont::text_width(const std::string& text, int scale) const {
    int max_width = 0;
    int width = 0;
    int char_w = CHAR_WIDTH * scale + CHAR_SPACING * scale;

    for (char c : text) {
        if (c == '\n') {
            max_width = std::max(max_width, width);
            width = 0;
        } else {
            width += char_w;
        }
    }

    max_width = std::max(max_width, width);
    if (max_width > 0) max_width -= CHAR_SPACING * scale; // No trailing space
    return max_width;
}

int BitmapFont::text_height(int scale) const {
    return CHAR_HEIGHT * scale;
}

void BitmapFont::draw_centered(Renderer& renderer, const std::string& text,
                                 int center_x, int y, const Color& color,
                                 int scale) const {
    int w = text_width(text, scale);
    draw_text(renderer, text, center_x - w / 2, y, color, scale);
}

